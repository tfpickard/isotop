/// The glyph for a character; anything outside printable ASCII is drawn as `?`.
pub fn glyph(character: char) -> u128 {
    let code = if character == ' ' || character.is_ascii_graphic() {
        character as usize
    } else {
        '?' as usize
    };
    GLYPHS[code - 0x20]
}
